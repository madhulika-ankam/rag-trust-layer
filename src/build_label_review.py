#!/usr/bin/env python3
"""
build_label_review.py — a 20-question worksheet for an external reviewer to
check the `expected_decision` labels.

WHY THIS EXISTS
    The 161 `expected_decision` labels were generated by a rule-based
    heuristic over the gold answers. Nobody with manufacturing expertise has
    confirmed that the protocol is sound, so Chapter 4 currently has to say
    the labels are heuristic and that decision accuracy is not validated.

    Twenty reviewed labels change that. They do not make the other 141
    correct, but they let the thesis report inter-annotator agreement on a
    sample instead of asserting the labels are right.

SAMPLING
    Stratified by machine and by label, with a fixed seed so the sample is
    reproducible and can be stated in the methodology. ESCALATE is
    deliberately over-sampled relative to its 37/161 share: those are the
    labels the heuristic is most likely to have got wrong, since it had to
    infer "the manuals do not support an answer" from the gold answer alone.

    The generated answer is NOT shown. The reviewer is checking whether the
    label is right for the QUESTION, not grading the system.

USAGE
    python -m src.build_label_review
    python -m src.build_label_review --n 10
"""
from __future__ import annotations

import argparse
import csv
import json
import random
from collections import defaultdict
from pathlib import Path

# Short names for the worksheet — the raw filenames are unreadable
MACHINE = {
    "KneeMill-Complete-Manual.pdf": "Bridgeport knee mill",
    "english---lathe-ngc---operator_s-manual---2018.pdf": "HAAS lathe",
    "710-965-00_UR5e_User_Manual_en_Global.pdf": "UR5e robot arm",
}

LABEL_MEANING = {
    "ANSWER": "manuals contain the answer - deliver it",
    "WARN": "partly supported - deliver with a caveat",
    "ESCALATE": "not supported by the manuals - withhold and say so",
    "REFUSE": "not supported by the manuals - withhold and say so",
}


def machine_of(rec: dict) -> str:
    chunks = rec.get("retrieved_chunks") or []
    if not chunks:
        return "other / regulation"
    return MACHINE.get(chunks[0]["source_file"], "other / regulation")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gen", type=Path,
                    default=Path("data/processed/generations.jsonl"))
    ap.add_argument("--out", type=Path,
                    default=Path("data/processed/label_review_morkos.csv"))
    ap.add_argument("--n", type=int, default=20)
    ap.add_argument("--seed", type=int, default=20261014)
    args = ap.parse_args()

    records = [json.loads(l) for l in args.gen.open(encoding="utf-8")]

    # Group by (machine, label) so the sample spans both
    strata: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for r in records:
        strata[(machine_of(r), r["expected_decision"])].append(r)

    rng = random.Random(args.seed)
    # Over-sample the non-ANSWER labels: 37 ESCALATE and 3 WARN out of 161,
    # but they carry most of the risk of being mislabelled.
    want = {"ESCALATE": 0.40, "WARN": 0.10, "ANSWER": 0.50}
    picked: list[dict] = []
    for label, share in want.items():
        pool = [r for (m, lab), rs in strata.items() if lab == label for r in rs]
        rng.shuffle(pool)
        target = round(args.n * share)
        # Spread across machines rather than taking the first N of a shuffle
        seen_machines: set[str] = set()
        chosen: list[dict] = []
        for r in pool:
            if len(chosen) >= target:
                break
            m = machine_of(r)
            if m in seen_machines and len(seen_machines) < 3:
                continue
            chosen.append(r)
            seen_machines.add(m)
            if len(seen_machines) == 3:
                seen_machines.clear()
        picked.extend(chosen[:target])

    picked.sort(key=lambda r: r["question_id"])

    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open("w", newline="", encoding="utf-8-sig") as fh:
        w = csv.writer(fh)
        # No machine column. machine_of() reads the top RETRIEVED chunk, so
        # it says where the system looked, not what the question is about —
        # q15 asks about the Bridgeport and comes out tagged "HAAS lathe".
        # It is reliable enough to stratify the sample and not reliable
        # enough to put in front of a reviewer. The question text says which
        # machine anyway.
        w.writerow(["question_id", "question",
                    "answer_in_the_manuals", "current_label",
                    "what_that_label_means",
                    "do_you_agree (yes/no/unsure)", "if_no_what_should_it_be",
                    "comment"])
        for r in picked:
            w.writerow([
                r["question_id"], r["question"],
                (r["gold_answer"] or "").strip()[:600],
                r["expected_decision"],
                LABEL_MEANING.get(r["expected_decision"], ""),
                "", "", "",
            ])

    from collections import Counter
    print(f"Wrote {len(picked)} rows to {args.out}")
    print("  by label  :", dict(Counter(r["expected_decision"] for r in picked)))
    print("  by machine:", dict(Counter(machine_of(r) for r in picked)))
    print(f"  seed {args.seed} — re-running reproduces this exact sample")


if __name__ == "__main__":
    main()
